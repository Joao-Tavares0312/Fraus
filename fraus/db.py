def _traduzir(sql: str) -> str:
    """Marcador posicional do SQLite (`?`) para o do psycopg (`%s`).

    Substituicao direta, e nao um parser: nenhuma consulta deste arquivo tem
    `?` ou `%` dentro de literal de texto -- todo valor entra por parametro,
    que e a mesma regra que ja impede injecao aqui. Se um dia entrar, este e o
    ponto que precisa ficar mais esperto.
    """
    return sql.replace("?", "%s")


class _ConexaoSqlite:
    """Conexao SQLite que de fato FECHA ao sair do `with`.

    `with sqlite3.connect(...)` faz commit e NAO fecha -- e uma pegadinha da
    biblioteca padrao. Como este modulo abre uma conexao POR CHAMADA, cada
    metodo deixava um descritor aberto para o coletor recolher quando desse na
    telha.

    Em Linux passa despercebido. No Windows o arquivo fica TRAVADO: apagar o
    diretorio temporario de um teste levanta `PermissionError [WinError 32]`.
    Foi assim que o defeito apareceu -- dois scripts diferentes quebraram no
    mesmo ponto antes de alguem procurar a causa.

    Existe tambem para emparelhar com `_ConexaoPostgres`: la o `__exit__`
    devolve a conexao ao pool, e ter um dialeto que solta o recurso e outro que
    nao solta e a assimetria que vira bug quando alguem le um caminho e assume
    o outro.
    """

    def __init__(self, conexao: sqlite3.Connection) -> None:
        self._conexao = conexao

    def execute(self, sql: str, parametros=()):
        return self._conexao.execute(sql, parametros)

    def executemany(self, sql: str, sequencia):
        return self._conexao.executemany(sql, sequencia)

    def executescript(self, sql: str):
        return self._conexao.executescript(sql)

    def __enter__(self) -> "_ConexaoSqlite":
        return self

    def __exit__(self, tipo, valor, traco) -> None:
        # Commit no caminho feliz e rollback no erro -- o mesmo contrato que o
        # `with` do sqlite3 ja dava e que todo metodo daqui assume. O `finally`
        # garante que a conexao fecha inclusive quando o proprio commit falha.
        try:
            if tipo is None:
                self._conexao.commit()
            else:
                self._conexao.rollback()
        finally:
            self._conexao.close()


class _ConexaoPostgres:
    """Conexao Postgres com a MESMA superficie que o codigo ja usava do SQLite.

    Existe para que os ~40 metodos abaixo continuem escritos em um dialeto so.
    A alternativa -- um `if self._postgres` dentro de cada metodo -- dobraria
    cada consulta e faria os dois caminhos divergirem no primeiro dia em que
    alguem mexesse em um sem lembrar do outro.

    O `?` vira `%s` na entrada, e `execute`/`executemany`/`fetchone` seguem
    devolvendo cursor e dicionario como antes.
    """

    def __init__(self, conexao) -> None:
        self._conexao = conexao

    def execute(self, sql: str, parametros=()):
        return self._conexao.execute(_traduzir(sql), parametros)

    def executemany(self, sql: str, sequencia):
        cursor = self._conexao.cursor()
        cursor.executemany(_traduzir(sql), list(sequencia))
        return cursor

    def executescript(self, sql: str) -> None:
        """DDL de varios comandos. O psycopg aceita direto, sem parametro."""
        self._conexao.execute(sql)

    def __enter__(self) -> "_ConexaoPostgres":
        return self

    def __exit__(self, tipo, valor, traco) -> None:
        # Commit no caminho feliz, rollback no erro -- o mesmo contrato do
        # `with` do sqlite3, que todo metodo daqui ja assumia. Devolver a
        # conexao ao pool e o extra: sem isso, cada chamada abriria um TLS novo
        # contra o Supabase e o pool secaria em poucas requisicoes.
        if tipo is None:
            self._conexao.commit()
        else:
            self._conexao.rollback()
        self._devolver()

    def _devolver(self) -> None:
        self._contexto.__exit__(None, None, None)


