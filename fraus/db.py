    def buscar_usuario_por_email(self, email: str) -> dict | None:
        # No SQLite a coluna e COLLATE NOCASE e o proprio `=` ja compara sem
        # caixa. No Postgres a comparacao precisa ser explicita -- e ela usa a
        # MESMA expressao do indice unico (`lower(email)`), de proposito: se as
        # duas divergissem, o banco recusaria o cadastro duplicado que a busca
        # nao acha, e o login diria "e-mail invalido" para uma conta existente.
        consulta = (
            "SELECT * FROM usuarios WHERE lower(email) = lower(?)"
            if self._postgres
            else "SELECT * FROM usuarios WHERE email = ?"
        )
        with self._conectar() as conexao:
            linha = conexao.execute(consulta, (email,)).fetchone()
        return self._usuario(linha) if linha is not None else None

