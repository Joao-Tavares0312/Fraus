        with self._conectar() as conexao:
            conexao.execute(
                self._upsert(
                    "conversas",
                    ("id", "canal", "iniciada_em", "score", "categoria", "payload",
                     "lexico_versao"),
                    ("id",),
                ),
                (
                    conversa.id,
                    conversa.canal,
                    conversa.iniciada_em.isoformat(),
                    score,
                    categoria,
                    conversa.model_dump_json(),
                    lexico_versao,
                ),
            )

