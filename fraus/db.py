    # Quantas entregas cada fonte guarda EM CADA BALDE. Registrar recusa de
    # assinatura e exatamente o que o operador precisa ver -- alguem esta
    # batendo com o segredo errado -- e e tambem como um atacante enche o
    # banco. A poda e o que permite manter a primeira propriedade sem pagar a
    # segunda.
    #
    # SAO DOIS BALDES, aceitas e o resto, e isto e conserto de 03/09/2026. Antes
    # a poda nao distinguia veredito, e as duas coisas disputavam as mesmas 200
    # vagas. Como a rota de webhook e isenta de chave de acesso por desenho -- a
    # plataforma externa nao tem como carregar uma `fra_` --, 210 requisicoes
    # anonimas com assinatura lixo zeravam as aceitas de uma fonte. Reproduzido
    # em 02/09/2026.
    #
    # O dano nao era so o historico: esta tabela e TAMBEM a memoria do dedupe
    # (`entrega_ja_vista`), entao apagar as aceitas fazia reentrega legitima
    # voltar a ser processada como nova. O comentario antigo aqui dizia que o
    # efeito era "limitado" porque `salvar` usa INSERT OR REPLACE e reprocessar
    # so repontua -- verdade para o dado, falsa para o custo: reprocessar e
    # inferencia de BERTimbau, e era um anonimo quem decidia quando ela roda.
    #
    # Dois baldes, e nao um por veredito: por veredito o teto viraria
    # 200 x len(VEREDITOS) e cresceria sozinho toda vez que alguem acrescentasse
    # um motivo de recusa. Aqui o teto por fonte e 2 x ENTREGAS_POR_FONTE, fixo.
    ENTREGAS_POR_FONTE = 200

    def registrar_entrega(
        self,
        fonte_id: int,
        webhook_id: str | None,
        veredito: str,
        recebida_em: str,
        motivo: str | None = None,
        conversa_id: str | None = None,
    ) -> None:
        """Registra a tentativa e poda as antigas DAQUELA fonte, numa transacao.

        A poda anda junto com o insert de proposito: separada, ela dependeria de
        alguem lembrar de chama-la, e o dia em que ninguem lembrasse seria o dia
        em que a tabela cresce sem teto.
        """
        with self._conectar() as conexao:
            conexao.execute(
                "INSERT INTO entregas_webhook "
                "(fonte_id, webhook_id, recebida_em, veredito, motivo, conversa_id) "
                "VALUES (?, ?, ?, ?, ?, ?)",
                (fonte_id, webhook_id, recebida_em, veredito, motivo, conversa_id),
            )
            # O corte usa o MESMO criterio de `listar_entregas`
            # (`recebida_em DESC, id DESC`), de proposito: `recebida_em` e
            # carimbado pelo servidor no instante em que a chamada chega (a
            # rota grava `datetime.now(timezone.utc)`, nunca um campo do
            # corpo) -- e tao interno quanto o `id`, entao nao ha razao para
            # os dois criterios divergirem. Com o mesmo criterio nos dois
            # lados, "as 200 que ficam" e "as 200 que aparecem" sao
            # literalmente o mesmo conjunto, na mesma ordem, por construcao.
            # `id` entra so como desempate, porque duas entregas podem
            # carimbar o mesmo instante ISO.
            #
            # OS DOIS BALDES sao selecionados separadamente e reunidos por
            # UNION ALL: cada um preserva as suas N mais recentes, e nenhum pode
            # despejar o outro. O `SELECT id FROM (...)` externo existe porque
            # nem SQLite nem Postgres aceitam LIMIT direto num operando de UNION.
            mais_recentes = (
                "SELECT id FROM (SELECT id FROM entregas_webhook "
                "WHERE fonte_id = ? AND veredito {comparador} 'aceita' "
                f"ORDER BY {self._ordem('recebida_em')} DESC, id DESC LIMIT ?) AS _{{apelido}}"
            )
            conexao.execute(
                "DELETE FROM entregas_webhook WHERE fonte_id = ? AND id NOT IN ("
                + mais_recentes.format(comparador="=", apelido="aceitas")
                + " UNION ALL "
                + mais_recentes.format(comparador="<>", apelido="recusadas")
                + ")",
                (
                    fonte_id,
                    fonte_id, self.ENTREGAS_POR_FONTE,
                    fonte_id, self.ENTREGAS_POR_FONTE,
                ),
            )

    def listar_entregas(self, fonte_id: int) -> list[dict]:
        """Entregas da fonte, mais recente primeiro.

        Ordena por `recebida_em` -- o horario que a chamada de fato chegou --
        com `id` como desempate. So por `id` colocaria a ordem de insercao na
        frente do horario real quando as duas divergem (ex.: reprocessamento
        fora de ordem), e e o horario que o operador espera ver no topo.
        """
        with self._conectar() as conexao:
            linhas = conexao.execute(
                "SELECT id, fonte_id, webhook_id, recebida_em, veredito, motivo, "
                "conversa_id FROM entregas_webhook WHERE fonte_id = ? "
                f"ORDER BY {self._ordem('recebida_em')} DESC, id DESC",
                (fonte_id,),
            ).fetchall()
        return [dict(linha) for linha in linhas]

    def entrega_ja_vista(self, fonte_id: int, webhook_id: str) -> bool:
        """Se aquele evento ja foi ACEITO por aqui. O dedupe e POR FONTE.

        Duas plataformas podem numerar eventos igual, e tratar o `msg_1` de uma
        como reentrega da outra descartaria atendimento em silencio.

        So conta veredito "aceita" -- de proposito. Uma RECUSA registrada
        (assinatura errada, variavel de ambiente ausente, fonte desativada) nao
        e uma entrega ja processada, e uma tentativa. Contar qualquer veredito
        aqui abre duas portas: um anonimo manda `webhook-id` alheio com
        assinatura lixo so para "queimar" aquele id antes da plataforma
        legitima entregar (a rota e ISENTA de chave de acesso, e o formato do
        id costuma ser previsivel); e, sem atacante nenhum, um operador que
        corrige a variavel de ambiente ou reativa a fonte depois de um 503/403
        veria a propria retentativa cair como "duplicada" e o atendimento se
        perder para sempre -- exatamente o caminho de recuperacao que a
        integracao existe para oferecer.
        """
        with self._conectar() as conexao:
            linha = conexao.execute(
                "SELECT 1 FROM entregas_webhook WHERE fonte_id = ? AND webhook_id = ? "
                "AND veredito = 'aceita' LIMIT 1",
                (fonte_id, webhook_id),
            ).fetchone()
        return linha is not None

    @staticmethod
    def _fonte(linha: sqlite3.Row) -> dict:
        """Fonte como ela pode circular. O HASH DA CHAVE NAO SAI POR AQUI.

        O `chave_hash` e removido neste unico ponto, e nao na borda HTTP, de
        proposito: `_fonte_publica` monta a resposta com `{**fonte}`, entao
        qualquer coluna nova da tabela apareceria sozinha na API sem ninguem
        decidir isso. Tirando o campo na origem, esquecer de esconder deixa de
        ser possivel -- quem precisa dele chama `hash_da_chave_da_fonte`, que e
        explicito no nome e no uso.

        O hash nao e senha e nem por isso pode circular: ele e o suficiente
        para confirmar um palpite de chave offline, sem nenhuma requisicao.
        """
        registro = dict(linha)
        registro["ativa"] = bool(registro["ativa"])
        registro.pop("chave_hash", None)
        return registro

